const out = document.getElementById("out"), txt = document.getElementById("in"), btn = document.getElementById("btn"), track = {};

function send(s, t) {
    const d = document.createElement("div"); d.className = "msg " + t; d.innerText = s; out.appendChild(d);
    out.scrollTop = out.scrollHeight; return d;
}

function run() {
    const v = txt.value.trim(); if (!v) return; send(v, "user"); txt.value = "";
    const c = " " + v.toLowerCase().replace(/[.,\/#!$%\^&\*;:{}=\-_`~()?]/g," ") + " ";
    let r = null;
    
    for (let i of db) {
        for (let k of i.k) {
            if (c.includes(" " + k + " ")) {
                if (track[k] === undefined) track[k] = 0;
                r = i.r[track[k] % i.r.length]; track[k]++; break;
            }
        }
        if (r) break;
    }
    
    if (!r) r = fb[Math.floor(Math.random() * fb.length)];
    const p = document.createElement("div"); p.className = "tip"; p.innerText = "Generating response...";
    out.appendChild(p); out.scrollTop = out.scrollHeight;
    
    setTimeout(() => { p.remove(); send(r, "bot"); }, 450);
}

btn.addEventListener("click", run); txt.addEventListener("keypress", e => { if (e.key === "Enter") run(); });
